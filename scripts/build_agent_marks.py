#!/usr/bin/env python3
"""Build the agent marks of ConductLoop from the identity kit.

The kit ("ConductLoop - Kit completo animado") delivers the twelve agent
glyphs on a board: a 1448x1086 PNG with a 4x3 grid of 362x362 cells, one per
role, plus one animated SVG per role. The SVG is a container: it embeds the
whole board as a raster and crops one cell with its viewBox, and it moves the
crop with a CSS transform.

Shipping that as it is would mean 66 MB of assets (the board is embedded
twice per role, plus a GIF), so the kit is **read, not copied**:

- each cell is cropped out of the board once and written as a small PNG,
  which is exactly what the SVG shows — the geometry is not touched;
- the movement is taken from the SVG's own keyframes, so the animation in
  the app is the one that was designed, not a new one.

The translations in the keyframes are in the SVG's user units (the cell is
362 units wide), so they are converted to percentages: the same movement
then works at any size the avatar is drawn at.

Usage:
    python3 scripts/build_agent_marks.py "/path/to/ConductLoop - Kit completo animado"

The output is committed to the repository, so the app never needs the kit.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "ops_dashboard" / "web" / "assets" / "agents"
OUT_CSS = ROOT / "ops_dashboard" / "web" / "agent-marks.css"

# The cell of the board is 362 units wide; the translations of the movement
# are in those units and become percentages of the avatar.
CELL = 362

# The avatar is drawn at 24, 32 and 56 pixels. 128 is enough for the
# largest of them on a retina screen.
SIZE = 128


def crop_cell(board, view_box: str):
    """The cell of the board that the role's SVG shows."""
    x, y, w, h = (float(v) for v in view_box.split())
    if (w, h) != (CELL, CELL):
        raise ValueError(f"unexpected cell {w}x{h}")
    return board.crop((int(x), int(y), int(x + w), int(y + h)))


def to_percent(keyframes: str) -> str:
    """The translations of the movement, in percentages of the avatar."""

    def one(match: re.Match) -> str:
        dx, dy = (float(v) for v in match.groups())
        return f"translate({dx / CELL * 100:.4f}%, {dy / CELL * 100:.4f}%)"

    return re.sub(r"translate\((-?[\d.]+)px,\s*(-?[\d.]+)px\)", one, keyframes)


def keyframes_of(style: str) -> str:
    """The body of the ``agent`` keyframes of the SVG's style.

    The style also carries the SVG's own reduced-motion rule, which talks
    about the class of the SVG; this one is not wanted here.
    """
    start = style.index("@keyframes agent{")
    depth, i = 1, start + len("@keyframes agent{")
    while i < len(style) and depth:
        if style[i] == "{":
            depth += 1
        elif style[i] == "}":
            depth -= 1
        i += 1
    return style[start + len("@keyframes agent{") : i - 1]


def build(kit: Path) -> int:
    try:
        from PIL import Image
    except ImportError:
        print("Pillow is needed: pip install pillow", file=sys.stderr)
        return 1

    manifest = json.loads((kit / "agentes.json").read_text(encoding="utf-8"))
    board = Image.open(kit / "assets" / "agentes.png").convert("RGB")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rules: list[str] = []
    total = 0

    for entry in manifest:
        role = entry["role"]
        svg = (kit / entry["svg"]).read_text(encoding="utf-8")
        view_box = re.search(r'<svg x="0" y="0"[^>]*viewBox="([^"]+)"', svg).group(1)

        cell = crop_cell(board, view_box)
        cell = cell.resize((SIZE, SIZE), Image.LANCZOS)
        target = OUT_DIR / f"{role}.png"
        cell.save(target, optimize=True)
        size = target.stat().st_size
        total += size

        animated = (kit / entry["animation"]).read_text(encoding="utf-8")
        style = re.search(r"<style>(.*?)</style>", animated, re.S).group(1)
        duration = re.search(r"animation:agent ([\d.]+)s", style).group(1)

        rules.append(
            f"/* {entry['name']} — {entry['motion']}, {duration}s */\n"
            f"@keyframes mark-{role} {{{to_percent(keyframes_of(style))}}}\n"
            f".mark-{role} {{ animation: mark-{role} {duration}s linear infinite; }}\n"
        )
        print(f"  {role:16s} {entry['motion']:8s} {duration}s  {size // 1024:>4d} KB")

    header = (
        "/* The agent marks of ConductLoop — generated by scripts/build_agent_marks.py.\n"
        "   The movement is the one designed in the identity kit, with the\n"
        "   translations in percentages so it works at any size. Do not edit by\n"
        "   hand: run the script again. */\n\n"
    )
    footer = (
        "/* Somebody who asked the system to move less gets the marks still. */\n"
        "@media (prefers-reduced-motion: reduce) {\n"
        "  [class*='mark-'] { animation: none !important; }\n"
        "}\n"
    )
    OUT_CSS.write_text(header + "\n".join(rules) + "\n" + footer, encoding="utf-8")

    print(f"\n{len(manifest)} marks -> {OUT_DIR.relative_to(ROOT)} "
          f"({total // 1024} KB in total)")
    print(f"movement -> {OUT_CSS.relative_to(ROOT)}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("kit", type=Path, help="the 'Kit completo animado' folder")
    args = parser.parse_args()
    if not args.kit.is_dir():
        print(f"not a folder: {args.kit}", file=sys.stderr)
        return 2
    return build(args.kit)


if __name__ == "__main__":
    raise SystemExit(main())
