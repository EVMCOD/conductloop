"""Code-file TODO/FIXME/HACK/XXX detector.

Scans source files inside indexed repos for TODO-style comments and
classifies them by:
  - language (py, ts, tsx, js, swift, go, rs, sh, md, etc)
  - priority (urgent / blocker / high / normal) via keyword inference
  - project_key (via repo path → projects.PROJECTS registry)
  - location (file:line)

Results are stored in the `code_todos` table and exposed via the UI as a
separate "Code TODOs" view per project.

This runs alongside the markdown todo indexer; it does not replace it.
"""
from __future__ import annotations

import re
from pathlib import Path

from .. import db
from .. import projects as projects_mod

# Files we scan by extension. Excludes binaries, lock files, generated.
SCAN_EXTENSIONS = {
    ".py", ".pyi", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs",
    ".swift", ".go", ".rs", ".rb", ".java", ".kt", ".cs", ".cpp", ".c", ".h",
    ".sh", ".bash", ".zsh", ".sql", ".html", ".css", ".scss",
    ".md", ".mdx", ".yaml", ".yml", ".toml",
}

# Specific filenames that are auto-generated noise (skip entirely).
SKIP_FILENAMES = {
    "next-env.d.ts", "expo-env.d.ts", "react-native-env.d.ts",
    "globals.d.ts", "remix.env.d.ts", "gatsby-env.d.ts",
    ".eslintrc.js", ".prettierrc.js",
}

# Generic NOTE patterns that are auto-generated boilerplate, not real todos.
NOISE_NOTE_RE = re.compile(
    r"(?i)(this file should not be edited|automatically generated|do not edit|"
    r"auto-?generated|generated by|do not modify|don'?t edit|"
    r"see https?://)"
)

# Patterns for various comment styles.
# Order matters: most specific first.
COMMENT_PATTERNS = [
    # Python: # comment
    re.compile(r"#\s*(?P<text>(?:TODO|FIXME|HACK|XXX|BUG|NOTE)\b[:\-].{2,300})"),
    # Swift / JS / TS / Go / Rust / etc: // comment
    re.compile(r"//\s*(?P<text>(?:TODO|FIXME|HACK|XXX|BUG|NOTE)\b[:\-].{2,300})"),
    # Block comments: /* ... */
    re.compile(r"/\*\s*(?P<text>(?:TODO|FIXME|HACK|XXX|BUG|NOTE)\b[:\-].{2,300})"),
    # HTML/XML: <!-- ... -->
    re.compile(r"<!--\s*(?P<text>(?:TODO|FIXME|HACK|XXX|BUG|NOTE)\b[:\-].{2,300})"),
    # SQL: -- comment
    re.compile(r"--\s*(?P<text>(?:TODO|FIXME|HACK|XXX|BUG|NOTE)\b[:\-].{2,300})"),
]

# Files to skip entirely (build artifacts, dependencies, generated).
# Matching is case-insensitive (see scan loop) so /Build/ matches /build/ etc.
SKIP_PATH_PARTS = (
    "/node_modules/", "/.venv/", "/venv/", "/env/", "/.venv312/", "/venv312/",
    "/dist/", "/build/", "/build_archive/", "/.next/", "/.turbo/",
    "/.open-next/", "/.svelte-kit/", "/.vercel/", "/.out/", "/coverage/",
    "/__pycache__/", "/.pytest_cache/", "/.mypy_cache/", "/.ruff_cache/",
    "/target/", "/Pods/", "/DerivedData/", "/.cargo/",
    "/.git/", "/.obsidian/", "/.idea/", "/.vscode/",
    "/data/ops.db", "/data/models/",
    "/site-packages/",  # Python venv site-packages
    "/.swiftpm/", "/.build/",
    "/ios/Pods/", "/ios/.build/",
    "/intermediates.noindex/",  # Xcode archive intermediates
)

# Priority inference. Order matters: more specific wins.
PRIORITY_RULES = [
    # urgent: critical bugs, blockers, security, data loss, prod-down
    (re.compile(
        r"\b(blocker|urgent|critical|asap|breaking|broken|security|"
        r"data\s*loss|prod\s*down|production\s*down|hotfix|regression|vuln|exploit|"
        r"urgentísimo|crítico|crítica|romper|rompe|fallar|fallo|bloquea|bloqueador)\b",
        re.I), "urgent"),
    # high: FIXME/BUG/XXX kind markers, must-do language, ticket refs
    (re.compile(
        r"\b(fixme|xxx|bug|broken\s+in|must\s+(fix|do|implement|handle|add|remove|update)|"
        r"needs?\s+to\s+(be\s+)?(fixed|done|handled|addressed|resolved)|"
        r"important|priority|required|"
        r"importante|pendiente\s+urgente|debería\s+arreglar)\b",
        re.I), "high"),
    # low: nice-to-have, future, maybe, exploratory
    (re.compile(
        r"\b(nice\s+to\s+have|nice-to-have|maybe|consider|future|optional|someday|"
        r"idea|explore|investigate\s+later|when\s+we\s+have\s+time|"
        r"quizas|algún\s+día|opcional|explorar)\b",
        re.I), "low"),
]

# Ticket references → urgent (actionable work). Lookbehind/lookahead avoid
# false positives like 'foo#123' or '#12abc' while still matching '#567' at
# sentence start (where \b fails because # is non-word).
TICKET_RE = re.compile(
    r"(?<![A-Za-z0-9])([A-Z]{2,10}-\d{1,6}|#\d{2,6}|JIRA-\d+|PROJ-\d+|GH-\d+)(?![A-Za-z0-9])"
)

# File-path priority boost: core paths get +1 level
CORE_PATH_PATTERNS = (
    re.compile(r"/(api|server|db|database|auth|security|payment|billing)/"),
    re.compile(r"\b(server|db|database|main|app|index)\.(py|ts|tsx|js|swift|go)\b"),
)

# Kind from tag
KIND_MAP = {
    "TODO": "todo", "FIXME": "fixme", "HACK": "hack",
    "XXX": "xxx", "BUG": "bug", "NOTE": "note",
}

# Priority order for boost comparisons
PRIORITY_ORDER = {"low": 0, "normal": 1, "high": 2, "urgent": 3}
PRIORITY_NAMES = {0: "low", 1: "normal", 2: "high", 3: "urgent"}


def _classify_priority(text: str) -> str:
    level = "normal"
    for pat, lvl in PRIORITY_RULES:
        if pat.search(text):
            level = lvl
            break
    # Ticket references boost to urgent (unless already urgent)
    if level != "urgent" and TICKET_RE.search(text):
        level = "urgent"
    return level


def _priority_from_kind(kind: str) -> str | None:
    """FIXME/BUG/HACK/XXX comments are typically more severe than TODO."""
    if kind in ("fixme", "bug", "hack", "xxx"):
        return "high"
    return None


def _priority_from_path(file_path: str) -> str | None:
    """Core paths (api/, db.py, server.py) get a +1 boost."""
    for pat in CORE_PATH_PATTERNS:
        if pat.search(file_path):
            return "high"
    return None


def _boost_priority(base: str, boost: str) -> str:
    """Combine base priority with a boost (max wins, never downgrade)."""
    base_level = PRIORITY_ORDER.get(base, 1)
    boost_level = PRIORITY_ORDER.get(boost, 1)
    return PRIORITY_NAMES[max(base_level, boost_level)]


def final_priority(text: str, kind: str, file_path: str) -> str:
    """Combine text-based + kind-based + path-based priority."""
    base = _classify_priority(text)
    for source in (_priority_from_kind(kind), _priority_from_path(file_path)):
        if source:
            base = _boost_priority(base, source)
    return base


def _kind_from_text(text: str) -> str:
    first = text.split(":", 1)[0].split("-", 1)[0].strip().upper()
    return KIND_MAP.get(first, "todo")


def _clean_text(text: str) -> str:
    """Strip block-comment markers from text."""
    text = text.strip()
    if text.endswith("*/"):
        text = text[:-2].rstrip()
    if text.endswith("*/"):
        text = text[:-2].rstrip()
    return text


def _classify_project(file_path: str) -> str | None:
    """Match a file path to a project_key via repo_paths."""
    for p in projects_mod.PROJECTS:
        for rp in p.repo_paths:
            if file_path.startswith(rp + "/") or file_path == rp:
                return p.key
    return None


def _scan_file(path: Path) -> list[dict]:
    """Scan a single file for TODO-style comments."""
    out: list[dict] = []
    try:
        if path.stat().st_size > 500_000:
            return out  # skip files > 500KB
        content = path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return out
    if not content:
        return out

    for lineno, line in enumerate(content.splitlines(), 1):
        for pat in COMMENT_PATTERNS:
            for m in pat.finditer(line):
                raw = _clean_text(m.group("text"))
                if not raw or len(raw) < 4:
                    continue
                # Skip obvious noise (URLs, version strings)
                if "http://" in raw or "https://" in raw:
                    continue
                # Skip auto-generated boilerplate notes
                if NOISE_NOTE_RE.search(raw):
                    continue
                kind = _kind_from_text(raw)
                out.append({
                    "content": raw[:280],
                    "kind": kind,
                    "priority": final_priority(raw, kind, str(path)),
                    "file_path": str(path),
                    "line": lineno,
                })
    return out


def run(root: str | None = None, save: bool = True) -> dict:
    """Scan all repos in PROJECTS for code TODOs. Returns counters."""
    counters = {"scanned": 0, "todos": 0, "errors": 0, "by_priority": {"urgent": 0, "high": 0, "normal": 0, "low": 0}}

    # Build list of roots: known repo paths, plus a few extras
    roots: list[Path] = []
    if root:
        roots.append(Path(root).expanduser())
    else:
        for p in projects_mod.PROJECTS:
            for rp in p.repo_paths:
                rp = Path(rp)
                if rp.exists() and rp.is_dir():
                    roots.append(rp)

    all_todos: list[dict] = []
    seen: set[tuple[str, int, str]] = set()  # (file, line, content) for dedupe

    for root in roots:
        for fpath in root.rglob("*"):
            # prune
            spath = str(fpath)
            if any(part.lower() in spath.lower() for part in SKIP_PATH_PARTS):
                continue
            if not fpath.is_file():
                continue
            if fpath.name in SKIP_FILENAMES:
                continue
            if fpath.suffix.lower() not in SCAN_EXTENSIONS:
                continue
            counters["scanned"] += 1
            try:
                items = _scan_file(fpath)
            except Exception:
                counters["errors"] += 1
                continue
            for item in items:
                key = (item["file_path"], item["line"], item["content"])
                if key in seen:
                    continue
                seen.add(key)
                item["project_key"] = _classify_project(item["file_path"])
                all_todos.append(item)
                counters["todos"] += 1
                counters["by_priority"][item["priority"]] = counters["by_priority"].get(item["priority"], 0) + 1

    if save:
        db.replace_code_todos(all_todos)
    return counters
