def mirror_path() -> Path:
    return db.vault_root() / "learning" / "lessons.md"


def sync_vault_mirror() -> Path | None:
    """Regenerate <vault>/learning/lessons.md when enabled; when disabled,
    remove it only if it is our generated file."""
    path = mirror_path()
    try:
        if _get_setting("lessons.vault_mirror", "0") != "1":
            if path.is_file() and path.read_text(encoding="utf-8", errors="replace").startswith(MIRROR_MARKER):
                path.unlink()
            return None
        rows = list_lessons(status="active", limit=1000)
        lines = [MIRROR_MARKER, "", "# Lecciones activas", ""]
        for scope in sorted({r["scope"] for r in rows}):
            lines += [f"## {scope}", ""] + [f"- {r['text']}" for r in rows if r["scope"] == scope] + [""]
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(prefix=".lessons.", dir=path.parent)
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines))
        os.replace(tmp, path)
        return path
    except OSError:
        log.warning("lessons vault mirror failed", exc_info=True)
        return None


def summary() -> dict:
    with db.db() as conn:
        rows = conn.execute("SELECT status, COUNT(*) AS n FROM lessons GROUP BY status").fetchall()
    return {s: 0 for s in STATUSES} | {r["status"]: int(r["n"]) for r in rows}
