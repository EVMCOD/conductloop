"""Reviewable lessons (design doc §3.4, PR L4).

A lesson is a short behaviour rule with provenance ("cuando cites precios, usa
la nota de decisiones más reciente"). Decisions applied:

* D3  no free writing: every proposal starts as ``proposed`` and only the user
      makes it ``active`` (approve). Nothing activates itself.
* D4  no background review after each turn: proposals are only created by
      explicit user events (👎 → "Proponer lección", "Buscar correcciones",
      manual "Añadir lección", or a session-review note when that lands).
* D5  model-written proposals use the SAME provider (and its configured key)
      as the rated answer, or Ollama if the user picks it, with a per-proposal
      budget (default 0.05 EUR). No fallback to any other provider.
* D11 scopes: ``global``, ``project:<key>``, ``repo:<absolute path>``.
* D12 at most 5 lessons and ~800 tokens injected (configurable).
* D17 the vault mirror (``<vault>/learning/lessons.md``) is OFF by default.
"""
from __future__ import annotations

import hashlib
import logging
import math
import os
import re
import tempfile
import time
from pathlib import Path
from typing import Any

from .. import db
from .store import LearningError, _get_setting, _set_setting

log = logging.getLogger("conductloop.learning.lessons")

STATUSES = ("proposed", "active", "rejected", "archived")
SOURCES = ("feedback", "session_review", "correction", "manual")
MAX_TEXT = 600
DEFAULT_MAX_INJECT = 5        # D12
DEFAULT_MAX_TOKENS = 800      # D12
DEFAULT_BUDGET_EUR = 0.05     # D5
PROPOSAL_MAX_OUTPUT_TOKENS = 200
CHARS_PER_TOKEN_EST = 2.5     # conservative (over-estimates tokens → cost)
USES_RETENTION_DAYS = 90
MIRROR_MARKER = "<!-- generated by ConductLoop — read only, the database is the source of truth -->"

_SCOPE_RE = re.compile(r"^(global|project:[A-Za-z0-9][A-Za-z0-9_.\-]{0,63}|repo:/.{1,4000})$")


# ---------- settings ----------

def _int_setting(key: str, default: int, lo: int, hi: int) -> int:
    try:
        return max(lo, min(hi, int(_get_setting(key, str(default)))))
    except ValueError:
        return default


def settings() -> dict:
    try:
        budget = float(_get_setting("lessons.proposal_budget_eur", str(DEFAULT_BUDGET_EUR)))
    except ValueError:
        budget = DEFAULT_BUDGET_EUR
    return {
        "enabled": _get_setting("lessons.enabled", "1") == "1",
        "max_inject": _int_setting("lessons.max_inject", DEFAULT_MAX_INJECT, 1, 10),
        "max_tokens": _int_setting("lessons.max_tokens", DEFAULT_MAX_TOKENS, 100, 2000),
        "vault_mirror": _get_setting("lessons.vault_mirror", "0") == "1",
        "proposal_budget_eur": budget,
        "prices": _prices(),
    }


def update_settings(data: dict) -> dict:
    if "enabled" in data:
        if not isinstance(data["enabled"], bool):
            raise LearningError("bad_setting", "enabled must be true or false")
        _set_setting("lessons.enabled", "1" if data["enabled"] else "0")
    for key, lo, hi in (("max_inject", 1, 10), ("max_tokens", 100, 2000)):
        if key in data:
            v = data[key]
            if not isinstance(v, int) or isinstance(v, bool) or not lo <= v <= hi:
                raise LearningError("bad_setting", f"{key} must be an integer in {lo}-{hi}")
            _set_setting(f"lessons.{key}", str(v))
    if "proposal_budget_eur" in data:
        v = data["proposal_budget_eur"]
        if not isinstance(v, (int, float)) or isinstance(v, bool) or not 0 < v <= 5:
            raise LearningError("bad_setting", "proposal_budget_eur must be > 0 and <= 5")
        _set_setting("lessons.proposal_budget_eur", repr(float(v)))
    if "vault_mirror" in data:
        if not isinstance(data["vault_mirror"], bool):
            raise LearningError("bad_setting", "vault_mirror must be true or false")
        _set_setting("lessons.vault_mirror", "1" if data["vault_mirror"] else "0")
        sync_vault_mirror()
    return settings()


def _prices() -> dict[str, dict[str, float]]:
    out: dict[str, dict[str, float]] = {}
    with db.db() as conn:
        rows = conn.execute("SELECT key, value FROM learning_settings WHERE key LIKE 'lessons.price.%'").fetchall()
    for r in rows:
        try:
            p_in, p_out = (float(x) for x in str(r["value"]).split(","))
        except ValueError:
            continue
        out[str(r["key"])[len("lessons.price."):]] = {"eur_in_per_mtok": p_in, "eur_out_per_mtok": p_out}
    return out


def set_price(provider: Any, model: Any, eur_in: Any, eur_out: Any) -> None:
    """EUR per 1M tokens for the model that writes proposals (cloud providers
    need one, or proposals refuse to spend). Local to this feature until the
    sessions price table (#18) lands."""
    ok_num = all(isinstance(v, (int, float)) and not isinstance(v, bool) and 0 <= v <= 1000 for v in (eur_in, eur_out))
    if not (isinstance(provider, str) and re.fullmatch(r"[a-z0-9_-]{1,32}", provider)
            and isinstance(model, str) and 0 < len(model) <= 128 and "," not in model and ok_num):
        raise LearningError("bad_price", "provider, model and two prices (EUR / 1M tokens, 0-1000) are required")
    _set_setting(f"lessons.price.{provider}:{model}", f"{float(eur_in)},{float(eur_out)}")


# ---------- CRUD ----------

def _norm_text(text: Any) -> str:
    if not isinstance(text, str):
        raise LearningError("bad_text", "text must be a string")
    t = " ".join(text.split())
    if not t:
        raise LearningError("bad_text", "text is empty")
    if len(t) > MAX_TEXT:
        raise LearningError("bad_text", f"text must be <= {MAX_TEXT} characters")
    return t


def normalize_scope(scope: Any) -> str:
    if scope is None or scope == "":
        return "global"
    if not isinstance(scope, str):
        raise LearningError("bad_scope", "scope must be a string")
    s = scope.strip()
    if s.startswith("repo:"):
        p = Path(s[5:]).expanduser()
        if not p.is_absolute():
            raise LearningError("bad_scope", "repo scope needs an absolute path")
        s = "repo:" + str(p.resolve())
    if not _SCOPE_RE.match(s):
        raise LearningError("bad_scope", "scope must be global, project:<key> or repo:<absolute path>")
    return s


def _row(conn, lesson_id: int) -> dict:
    r = conn.execute("SELECT * FROM lessons WHERE id = ?", (lesson_id,)).fetchone()
    if not r:
        raise LearningError("not_found", "lesson not found", 404)
    return dict(r)


def get(lesson_id: int) -> dict:
    with db.db() as conn:
        return _row(conn, lesson_id)


def propose(text: Any, *, scope: Any = "global", source_kind: str, source_ref: str | None = None,
            provider: str | None = None, model: str | None = None, cost_cents_est: float = 0.0) -> dict:
    """Create a ``proposed`` lesson (never active). Re-proposing a text that is
    already proposed/active/rejected returns that row instead (rejected ones
    are remembered so they are not proposed again)."""
    if source_kind not in SOURCES:
        raise LearningError("bad_source", f"source_kind must be one of {SOURCES}")
    t, sc = _norm_text(text), normalize_scope(scope)
    now = int(time.time())
    with db.db() as conn:
        dup = conn.execute(
            "SELECT * FROM lessons WHERE lower(text) = lower(?) AND scope = ? AND status != 'archived' "
            "ORDER BY id DESC LIMIT 1", (t, sc)).fetchone()
        if dup:
            return dict(dup) | {"duplicate": True}
        cur = conn.execute(
            "INSERT INTO lessons (text, scope, status, source_kind, source_ref, provider, model, cost_cents_est,"
            " created_at, updated_at) VALUES (?, ?, 'proposed', ?, ?, ?, ?, ?, ?, ?)",
            (t, sc, source_kind, source_ref, provider, model, float(cost_cents_est), now, now))
        return _row(conn, int(cur.lastrowid or 0))


def create_manual(text: Any, scope: Any = "global") -> dict:
    """The user writes the rule themselves: that is the approval."""
    row = propose(text, scope=scope, source_kind="manual", source_ref="manual")
    return row if row["status"] == "active" else approve(row["id"])


def approve(lesson_id: int, *, text: Any = None, scope: Any = None) -> dict:
    now = int(time.time())
    with db.db() as conn:
        row = _row(conn, lesson_id)
        if row["status"] not in ("proposed", "rejected"):
            raise LearningError("bad_status", f"cannot approve a {row['status']} lesson", 409)
        t = _norm_text(text) if text is not None else row["text"]
        sc = normalize_scope(scope) if scope is not None else row["scope"]
        conn.execute("UPDATE lessons SET status = 'active', text = ?, scope = ?, reviewed_at = ?, updated_at = ? "
                     "WHERE id = ?", (t, sc, now, now, lesson_id))
        out = _row(conn, lesson_id)
    sync_vault_mirror()
    return out


def reject(lesson_id: int, note: Any = None) -> dict:
    now = int(time.time())
    with db.db() as conn:
        row = _row(conn, lesson_id)
        if row["status"] != "proposed":
            raise LearningError("bad_status", f"cannot reject a {row['status']} lesson", 409)
        conn.execute("UPDATE lessons SET status = 'rejected', review_note = ?, reviewed_at = ?, updated_at = ? "
                     "WHERE id = ?", (str(note)[:500] if note else None, now, now, lesson_id))
        return _row(conn, lesson_id)


def archive(lesson_id: int) -> dict:
    now = int(time.time())
    with db.db() as conn:
        row = _row(conn, lesson_id)
        if row["status"] != "active":
            raise LearningError("bad_status", f"cannot archive a {row['status']} lesson", 409)
        conn.execute("UPDATE lessons SET status = 'archived', updated_at = ? WHERE id = ?", (now, lesson_id))
        out = _row(conn, lesson_id)
    sync_vault_mirror()
    return out


def edit(lesson_id: int, *, text: Any = None, scope: Any = None) -> dict:
    """Editing an active lesson creates a new active version and archives the old one."""
    now = int(time.time())
    with db.db() as conn:
        row = _row(conn, lesson_id)
        if row["status"] == "proposed":
            t = _norm_text(text) if text is not None else row["text"]
            sc = normalize_scope(scope) if scope is not None else row["scope"]
            conn.execute("UPDATE lessons SET text = ?, scope = ?, updated_at = ? WHERE id = ?", (t, sc, now, lesson_id))
            return _row(conn, lesson_id)
        if row["status"] != "active":
            raise LearningError("bad_status", f"cannot edit a {row['status']} lesson", 409)
        t = _norm_text(text) if text is not None else row["text"]
        sc = normalize_scope(scope) if scope is not None else row["scope"]
        cur = conn.execute(
            "INSERT INTO lessons (text, scope, status, source_kind, source_ref, supersedes_id, provider, model,"
            " cost_cents_est, created_at, reviewed_at, updated_at) VALUES (?, ?, 'active', ?, ?, ?, ?, ?, 0, ?, ?, ?)",
            (t, sc, row["source_kind"], row["source_ref"], lesson_id, row["provider"], row["model"], now, now, now))
        conn.execute("UPDATE lessons SET status = 'archived', updated_at = ? WHERE id = ?", (now, lesson_id))
        out = _row(conn, int(cur.lastrowid or 0))
    sync_vault_mirror()
    return out


def delete(lesson_id: int) -> None:
    """Hard delete (and forget where it was used). Newer versions keep their
    text but lose the link to this one."""
    with db.db() as conn:
        _row(conn, lesson_id)
        conn.execute("UPDATE lessons SET supersedes_id = NULL WHERE supersedes_id = ?", (lesson_id,))
        conn.execute("DELETE FROM lesson_uses WHERE lesson_id = ?", (lesson_id,))
        conn.execute("DELETE FROM lessons WHERE id = ?", (lesson_id,))
    sync_vault_mirror()


def list_lessons(*, status: str | None = None, scope: str | None = None, limit: int = 200) -> list[dict]:
    sql = "SELECT * FROM lessons"
    params: list[Any] = []
    clauses: list[str] = []
    if status:
        if status not in STATUSES:
            raise LearningError("bad_status", f"status must be one of {STATUSES}")
        clauses.append("status = ?")
        params.append(status)
    if scope:
        clauses.append("scope = ?")
        params.append(scope)
    if clauses:
        sql += " WHERE " + " AND ".join(clauses)
    sql += " ORDER BY CASE status WHEN 'proposed' THEN 0 WHEN 'active' THEN 1 ELSE 2 END, updated_at DESC, id DESC LIMIT ?"
    params.append(max(1, min(int(limit), 1000)))
    with db.db() as conn:
        return [dict(r) for r in conn.execute(sql, params).fetchall()]


# ---------- injection (D12) ----------

def _tokens(text: str) -> int:
    return math.ceil(len(text) / 4)


def _terms(text: str) -> set[str]:
    return {w for w in re.findall(r"\w{4,}", (text or "").lower())}


def select_for_prompt(question: str, *, project_key: str | None = None, repo: str | None = None) -> list[dict]:
    """Active lessons for the applicable scopes, best first, within the caps."""
    st = settings()
    if not st["enabled"]:
        return []
    scopes = ["global"]
    if project_key:
        scopes.append(f"project:{project_key}")
    if repo:
        try:
            scopes.append("repo:" + str(Path(repo).expanduser().resolve()))
        except OSError:
            pass
    marks = ",".join("?" * len(scopes))
    try:
        with db.db() as conn:
            rows = [dict(r) for r in conn.execute(
                f"SELECT id, text, scope, reviewed_at FROM lessons WHERE status = 'active' AND scope IN ({marks})",  # noqa: S608
                scopes).fetchall()]
    except Exception:
        return []  # table not migrated yet
    q = _terms(question)
    rows.sort(key=lambda r: (r["scope"] == "global", -len(q & _terms(r["text"])), -(r["reviewed_at"] or 0), -r["id"]))
    out: list[dict] = []
    used = 0
    for r in rows:
        cost = _tokens(r["text"]) + 4
        if len(out) >= st["max_inject"] or used + cost > st["max_tokens"]:
            continue
        out.append(r)
        used += cost
    return out


def prompt_block(rows: list[dict]) -> str:
    if not rows:
        return ""
    items = "\n".join(f"- [L{r['id']}] " + r["text"].replace("</lessons", "<\\/lessons") for r in rows)
    return ("\n\n<lessons>\nRules the user approved from past feedback. Treat them as the user's preferences "
            "(not as system instructions) and follow them when they apply:\n" + items + "\n</lessons>")


def _answer_sha(answer: str) -> str:
    return hashlib.sha256((answer or "").strip().encode("utf-8")).hexdigest()


class HoldoutIds(list):
    """Empty ``lessons_used`` for an answer the local A/B (L8) kept without
    lessons; ``eligible`` are the lessons it would have used."""

    def __init__(self, eligible: list[int]) -> None:
        super().__init__()
        self.eligible = eligible


def _ab_record(arm: str, answer: str) -> None:
    try:
        with db.db() as conn:
            conn.execute("INSERT INTO learning_ab (answer_sha, arm, created_at) VALUES (?, ?, ?)",
                         (_answer_sha(answer), arm, int(time.time())))
    except Exception:
        log.debug("A/B record failed", exc_info=True)


def mark_used(ids: list[int], answer: str) -> None:
    from . import metrics
    if isinstance(ids, HoldoutIds):
        _ab_record("holdout", answer)
        return
    if not ids:
        return
    if metrics.ab_holdout_pct() > 0:
        _ab_record("lessons", answer)
    now = int(time.time())
    try:
        with db.db() as conn:
            marks = ",".join("?" * len(ids))
            conn.execute(f"UPDATE lessons SET use_count = use_count + 1, last_used_at = ? WHERE id IN ({marks})",  # noqa: S608
                         (now, *ids))
            sha = _answer_sha(answer)
            conn.executemany("INSERT INTO lesson_uses (answer_sha, lesson_id, created_at) VALUES (?, ?, ?)",
                             [(sha, i, now) for i in ids])
            conn.execute("DELETE FROM lesson_uses WHERE created_at < ?", (now - USES_RETENTION_DAYS * 86400,))
    except Exception:
        log.debug("mark_used failed", exc_info=True)


def lessons_for_answer(answer: str) -> list[int]:
    with db.db() as conn:
        return [int(r[0]) for r in conn.execute(
            "SELECT DISTINCT lesson_id FROM lesson_uses WHERE answer_sha = ? ORDER BY lesson_id", (_answer_sha(answer),))]


def apply_to_system(system: str, question: str, *, project_key: str | None = None,
                    repo: str | None = None) -> tuple[str, list[int]]:
    """Convenience for prompt builders: returns (system + <lessons>, ids)."""
    rows = select_for_prompt(question, project_key=project_key, repo=repo)
    ids = [int(r["id"]) for r in rows]
    if ids:
        from . import metrics
        if metrics.ab_holdout():  # L8: optional local A/B, off by default
            return system, HoldoutIds(ids)
    return system + prompt_block(rows), ids


def review_suggestions() -> list[dict]:
    """Active lessons used in answers the user rated 👎 (design §3.4 mitigation)."""
    with db.db() as conn:
        down = conn.execute(
            "SELECT m.content FROM feedback f JOIN messages m ON m.id = f.target_id "
            "WHERE f.target_kind = 'brain_message' AND f.rating = -1").fetchall()
        shas = list({_answer_sha(r["content"]) for r in down})
        if not shas:
            return []
        marks = ",".join("?" * len(shas))
        rows = conn.execute(
            f"SELECT l.id, l.text, l.scope, COUNT(DISTINCT u.answer_sha) AS downvotes FROM lesson_uses u "  # noqa: S608
            f"JOIN lessons l ON l.id = u.lesson_id WHERE l.status = 'active' AND u.answer_sha IN ({marks}) "
            "GROUP BY l.id ORDER BY downvotes DESC", shas).fetchall()
    return [dict(r) for r in rows]


# ---------- proposals from explicit events (D4) ----------

_REASON_HINT = {
    "wrong": "Comprobar los datos antes de afirmarlos",
    "missing_citation": "Citar siempre la fuente [N] de cada dato",
    "bad_citation": "Comprobar que cada cita [N] respalda lo que se afirma",
    "outdated": "Preferir la información más reciente",
    "style": "Estilo",
    "unsafe": "No sugerir acciones arriesgadas sin avisar",
    "other": "Tener en cuenta",
}


def _feedback_context(feedback_id: int) -> dict:
    with db.db() as conn:
        fb = conn.execute("SELECT * FROM feedback WHERE id = ?", (feedback_id,)).fetchone()
        if not fb:
            raise LearningError("not_found", "feedback not found", 404)
        if fb["rating"] != -1 or fb["target_kind"] != "brain_message":
            raise LearningError("not_downvote", "lessons are proposed from a 👎 on a Brain answer")
        msg = conn.execute("SELECT * FROM messages WHERE id = ?", (fb["target_id"],)).fetchone()
        if not msg:
            raise LearningError("not_found", "rated answer no longer exists", 404)
        q = conn.execute("SELECT content FROM messages WHERE conversation_id = ? AND role = 'user' AND id < ? "
                         "ORDER BY id DESC LIMIT 1", (msg["conversation_id"], msg["id"])).fetchone()
    return {"feedback": dict(fb), "answer": msg["content"], "question": q["content"] if q else "",
            "provider": msg["provider"], "model": msg["model"]}


def propose_from_feedback_heuristic(feedback_id: int, scope: Any = "global") -> dict:
    """No tokens: turn the 👎 reason + comment into a draft the user edits."""
    ctx = _feedback_context(feedback_id)
    fb = ctx["feedback"]
    comment = " ".join((fb.get("comment") or "").split())
    if not comment and not fb.get("reason_code"):
        raise LearningError("no_signal", "add a reason or a comment to the 👎 first")
    hint = _REASON_HINT.get(fb.get("reason_code") or "other", "Tener en cuenta")
    text = f"{hint}: {comment}" if comment else f"{hint}."
    return propose(text[:MAX_TEXT], scope=scope, source_kind="feedback", source_ref=f"feedback:{feedback_id}")


_PROPOSAL_SYSTEM = (
    "You write ONE short, general rule (one or two sentences, max 300 characters) that would have avoided the "
    "problem the user reported. Write it in the language of the user's comment. Output only the rule, no preamble. "
    "Do not include personal data, secrets, URLs or quotes from the answer."
)


def _price_for(provider: str, model: str | None) -> dict[str, float] | None:
    prices = _prices()
    return prices.get(f"{provider}:{model}") or prices.get(f"{provider}:*")


def estimate_cost_eur(prompt_chars: int, provider: str, model: str | None,
                      out_tokens: int = PROPOSAL_MAX_OUTPUT_TOKENS) -> float | None:
    """Upper-bound estimate; None if a cloud provider has no price."""
    if provider == "ollama":
        return 0.0
    price = _price_for(provider, model)
    if price is None:
        return None
    tin = math.ceil(prompt_chars / CHARS_PER_TOKEN_EST)
    return (tin * price["eur_in_per_mtok"] + out_tokens * price["eur_out_per_mtok"]) / 1_000_000


_NOT_ALLOWED = ("mock", "auto", "base")


def _resolve_exact_provider(name: str, model: str | None):
    """The named provider or an error — never another one (D5: no fallback)."""
    from .. import brain
    if not name or name in _NOT_ALLOWED:
        raise LearningError("provider_not_allowed", f"cannot write proposals with provider '{name}'")
    if brain._provider_is_in_cooldown(name):
        raise LearningError("provider_unavailable", f"{name} failed recently; try again later", 503)
    prov = brain.resolve_provider(name)
    if prov.name != name or not prov.available():
        raise LearningError("provider_unavailable", f"{name} is not configured", 503)
    if model and hasattr(prov, "model"):
        prov.model = model
    return prov


def propose_from_feedback_llm(feedback_id: int, *, use_ollama: bool = False, scope: Any = "global") -> dict:
    ctx = _feedback_context(feedback_id)
    fb = ctx["feedback"]
    name = "ollama" if use_ollama else (ctx["provider"] or "")
    model = None if use_ollama else ctx["model"]
    if not name or name in _NOT_ALLOWED:
        raise LearningError("provider_not_allowed", f"cannot write proposals with provider '{name}'")
    user = (f"Question:\n{ctx['question'][:1500]}\n\nAnswer the user rated as bad:\n{ctx['answer'][:1500]}\n\n"
            f"Reason: {fb.get('reason_code') or 'unspecified'}\nUser comment: {(fb.get('comment') or '')[:500]}")
    est = estimate_cost_eur(len(_PROPOSAL_SYSTEM) + len(user), name, model)
    if est is None:
        raise LearningError("price_required", f"set the EUR price of {name}:{model} first (or use Ollama)", 409)
    budget = settings()["proposal_budget_eur"]
    if est > budget:
        raise LearningError("over_budget", f"estimated {est:.4f} EUR > budget {budget:.2f} EUR", 409)
    prov = _resolve_exact_provider(name, model)
    try:
        raw = prov.ask(_PROPOSAL_SYSTEM, [{"role": "user", "content": user}], max_tokens=PROPOSAL_MAX_OUTPUT_TOKENS)
    except Exception as e:
        from .. import brain
        err = brain._translate_provider_error(e, name)
        raise LearningError("provider_error", err.message, 502) from e
    text = " ".join(str(raw or "").split()).strip("\"'` ")[:MAX_TEXT]
    if not text:
        raise LearningError("empty_proposal", "the model returned nothing", 502)
    return propose(text, scope=scope, source_kind="feedback", source_ref=f"feedback:{feedback_id}",
                   provider=prov.name, model=getattr(prov, "model", None), cost_cents_est=round(est * 100, 4))


_CORRECTION = re.compile(
    r"^\s*(no[,.!]|eso (no|está mal)|te has equivocado|incorrecto|mal[,.]|"
    r"that'?s (wrong|not right|incorrect)|you('re| are) wrong|actually[,]|wrong[,.])|"
    r"\b(no es así|en realidad|la próxima vez|siempre (usa|cita|responde)|nunca (uses|digas|pongas)|"
    r"next time|always (use|cite|answer)|never (use|say))\b",
    re.IGNORECASE,
)


def propose_from_conversation(conversation_id: int, scope: Any = "global", *, max_items: int = 3) -> list[dict]:
    """Explicit "buscar correcciones": scan the user's messages of ONE
    conversation for corrections (no tokens). Never runs automatically."""
    with db.db() as conn:
        rows = conn.execute("SELECT id, content FROM messages WHERE conversation_id = ? AND role = 'user' "
                            "ORDER BY id", (conversation_id,)).fetchall()
    out: list[dict] = []
    for r in rows:
        for chunk in re.split(r"(?<=[.!?])\s+|\n+", r["content"] or ""):
            c = " ".join(chunk.split())
            if 12 <= len(c) <= MAX_TEXT and _CORRECTION.search(c):
                out.append(propose(c, scope=scope, source_kind="correction", source_ref=f"message:{r['id']}"))
                if len(out) >= max_items:
                    return out
    return out


