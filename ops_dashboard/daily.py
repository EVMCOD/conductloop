"""Generate a daily note in the Obsidian vault capturing the day's activity.

Output: $OPS_VAULT_ROOT/daily/YYYY-MM-DD.md (or custom path)
Contains: brain conversations, closed todos, new ideas, URL changes,
diff vs yesterday, git activity from watched repos.

Use:
    python -m ops_dashboard daily [YYYY-MM-DD]  # default: today
    python -m ops_dashboard daily 2026-06-19    # specific day
"""
from __future__ import annotations

import os
from datetime import datetime
from pathlib import Path

from . import db

VAULT_DAILY = Path.home() / "Documents" / "Obsidian" / "OC" / "daily"


def collect_day(day: str) -> dict:
    """Collect all events for a given day (YYYY-MM-DD)."""
    start = int(datetime.strptime(day, "%Y-%m-%d").timestamp())
    end = start + 86399
    out = {"day": day, "brain_convos": [], "todos_completed": [], "ideas": [], "urls": [], "docs": []}
    # Brain conversations
    with db.db() as conn:
        rows = conn.execute(
            "SELECT id, title, created_at FROM conversations WHERE created_at >= ? AND created_at <= ? ORDER BY created_at",
            (start, end),
        ).fetchall()
        for r in rows:
            msgs = conn.execute(
                "SELECT role, content FROM messages WHERE conversation_id = ? ORDER BY created_at",
                (r["id"],),
            ).fetchall()
            if not msgs: continue
            out["brain_convos"].append({
                "id": r["id"], "title": r["title"], "created": r["created_at"],
                "messages": [dict(m) for m in msgs],
            })
        # User todos completed today
        rows = conn.execute(
            "SELECT * FROM user_todos WHERE status = 'done' AND completed_at >= ? AND completed_at <= ?",
            (start, end),
        ).fetchall()
        out["todos_completed"] = [dict(r) for r in rows]
        # Ideas created today
        rows = conn.execute(
            "SELECT * FROM ideas WHERE created_at >= ? AND created_at <= ?",
            (start, end),
        ).fetchall()
        out["ideas"] = [dict(r) for r in rows]
        # Documents modified today
        rows = conn.execute(
            "SELECT source, path, title, mtime FROM documents WHERE mtime >= ? AND mtime <= ? ORDER BY mtime DESC LIMIT 50",
            (start, end),
        ).fetchall()
        out["docs"] = [dict(r) for r in rows]
    # URL health: latest check vs the one before
    snaps = db.recent_snapshots(kind="auto", limit=7)
    if snaps:
        snap_today = db.get_snapshot(day, "auto")
        snap_yest = db.get_previous_snapshot(day, "auto")
        if snap_today and snap_yest:
            today_urls = {u["name"]: u for u in snap_today.get("url_status", [])}
            yest_urls = {u["name"]: u for u in snap_yest.get("url_status", [])}
            for name, u in today_urls.items():
                if name in yest_urls and yest_urls[name]["ok"] != u["ok"]:
                    out["urls"].append({
                        "name": name, "url": u["url"],
                        "from": yest_urls[name]["ok"], "to": u["ok"],
                    })
    return out


def render_markdown(data: dict) -> str:
    lines = [f"# {data['day']}", ""]
    lines.append(f"_Auto-generated by ops-dashboard at {datetime.now().strftime('%H:%M')}_")
    lines.append("")
    # Summary
    lines.append("## Summary")
    lines.append("")
    lines.append(f"- 🧠 {len(data['brain_convos'])} brain conversations")
    lines.append(f"- ☑ {len(data['todos_completed'])} todos completed")
    lines.append(f"- ✦ {len(data['ideas'])} ideas captured")
    lines.append(f"- 📄 {len(data['docs'])} documents touched")
    lines.append(f"- 🔗 {len(data['urls'])} URL state changes")
    lines.append("")
    # Brain conversations
    if data['brain_convos']:
        lines.append("## 🧠 Brain conversations")
        lines.append("")
        for c in data['brain_convos']:
            ts = datetime.fromtimestamp(c['created']).strftime('%H:%M')
            lines.append(f"### {ts} — {c['title']}")
            lines.append("")
            for m in c['messages']:
                who = f"**{os.environ.get('OPS_OWNER_NAME', 'You')}**" if m['role'] == 'user' else "**Brain**"
                # Truncate long messages
                content = m['content']
                if len(content) > 600: content = content[:600] + "…"
                lines.append(f"{who}: {content}")
                lines.append("")
        lines.append("")
    # Todos
    if data['todos_completed']:
        lines.append("## ☑ Completed todos")
        lines.append("")
        for t in data['todos_completed']:
            proj = f" ({t['project_key']})" if t.get('project_key') else ""
            lines.append(f"- ✓ {t['content']}{proj}")
        lines.append("")
    # Ideas
    if data['ideas']:
        lines.append("## ✦ Ideas")
        lines.append("")
        for i in data['ideas']:
            proj = f" ({i['project_key']})" if i.get('project_key') else ""
            status = f" *[{i['status']}]*" if i.get('status') != 'new' else ""
            lines.append(f"- {i['content']}{proj}{status}")
        lines.append("")
    # URL changes
    if data['urls']:
        lines.append("## 🔗 URL health changes")
        lines.append("")
        for u in data['urls']:
            arrow = "🟢" if u['to'] else "🔴"
            lines.append(f"- {arrow} {u['name']} ({u['from']} → {u['to']}) — {u['url']}")
        lines.append("")
    # Documents
    if data['docs']:
        lines.append("## 📄 Documents touched")
        lines.append("")
        for d in data['docs'][:30]:
            ts = datetime.fromtimestamp(d['mtime']).strftime('%H:%M')
            lines.append(f"- `{ts}` [{d['source']}] {d['title'] or d['path'].split('/')[-1]}")
        if len(data['docs']) > 30:
            lines.append(f"- ... and {len(data['docs']) - 30} more")
        lines.append("")
    return "\n".join(lines)


def vault_summary(day: str) -> dict:
    """What happened in the vault itself that day.

    The rest of the note is about the product (conversations, todos, URLs).
    This is about the notes: which ones were touched, which projects they
    belong to, and which ideas keep coming back.
    """
    from . import notes_structure

    start = int(datetime.strptime(day, "%Y-%m-%d").timestamp())
    end = start + 86399
    out: dict = {"notes": [], "projects": [], "ideas": []}
    try:
        with db.db() as conn:
            rows = conn.execute(
                "SELECT title, path, project_key, source FROM documents "
                "WHERE mtime >= ? AND mtime <= ? ORDER BY mtime DESC LIMIT 200",
                (start, end),
            ).fetchall()
    except Exception:
        rows = []
    per_project: dict[str, int] = {}
    for r in rows:
        title = r["title"] or Path(r["path"]).stem
        out["notes"].append({"title": title, "path": r["path"],
                            "project": r["project_key"] or "",
                            "source": r["source"]})
        key = r["project_key"] or ""
        if key:
            per_project[key] = per_project.get(key, 0) + 1
    out["projects"] = sorted(per_project.items(), key=lambda kv: -kv[1])
    try:
        out["ideas"] = notes_structure.propose_ideas()[:5]
    except Exception:
        out["ideas"] = []
    return out


def render_vault(data: dict) -> list[str]:
    """The vault half of the daily note."""
    lines: list[str] = []
    if not data.get("notes") and not data.get("projects"):
        return lines
    lines.append("## 🗺️ El vault")
    lines.append("")
    projects = data.get("projects") or []
    if projects:
        names = {p.key: p.name for p in _projects()}
        lines.append("**Proyectos que se movieron**")
        lines.append("")
        for key, count in projects[:8]:
            lines.append(f"- {names.get(key, key)} — {count} nota(s)")
        lines.append("")
    ideas = data.get("ideas") or []
    if ideas:
        lines.append("**Temas que se repiten**")
        lines.append("")
        for idea in ideas:
            lines.append(f"- {idea['title']} — {idea['notes']} notas")
        lines.append("")
    notes = data.get("notes") or []
    if notes:
        lines.append("**Notas tocadas**")
        lines.append("")
        for note in notes[:25]:
            name = Path(note["path"]).stem
            lines.append(f"- [[{name}]] — {note['title']}")
        if len(notes) > 25:
            lines.append(f"- … y {len(notes) - 25} más")
        lines.append("")
    return lines


def _projects():
    from . import projects as _p

    try:
        return _p.PROJECTS
    except Exception:
        return []


BLOCK_BEGIN = "<!-- conductloop:daily -->"
BLOCK_END = "<!-- /conductloop:daily -->"


def write_daily(day: str | None = None, out_dir: Path | None = None) -> Path:
    """Write the day's note, without ever destroying the user's own words.

    The daily note is a note the user writes in, not a report the product
    prints over: the generated part lives in a marked block and only that
    block is ever replaced.
    """
    day = day or datetime.now().strftime("%Y-%m-%d")
    out_dir = out_dir or VAULT_DAILY
    out_dir.mkdir(parents=True, exist_ok=True)
    data = collect_day(day)
    md = render_markdown(data)
    vault_lines = render_vault(vault_summary(day))
    if vault_lines:
        md = md.rstrip() + "\n\n" + "\n".join(vault_lines)
    block = f"{BLOCK_BEGIN}\n{md.rstrip()}\n{BLOCK_END}\n"

    out = out_dir / f"{day}.md"
    current = ""
    if out.exists():
        try:
            current = out.read_text(encoding="utf-8")
        except OSError:
            current = ""
    if BLOCK_BEGIN in current and BLOCK_END in current:
        start = current.index(BLOCK_BEGIN)
        end = current.index(BLOCK_END) + len(BLOCK_END)
        text = current[:start] + block.rstrip("\n") + current[end:]
    elif current.strip():
        # The user's note stays; the generated part goes under it.
        text = current.rstrip() + "\n\n" + block
    else:
        # Even a fresh note carries the markers: the block has to be
        # replaceable tomorrow, and it is what tells the product which part
        # is not the user's.
        text = block
    out.write_text(text, encoding="utf-8")
    return out
